"""Read-only parity audit of the two isolated SQL sources and a fresh MDX run.

Run read_cases.ps1 -Output .../readonly_recheck_mdx immediately before this
script. It never deploys/processes, changes permissions, or mutates SQL data.
"""

from __future__ import annotations

from datetime import datetime, timezone
import hashlib
import importlib.util
import json
from pathlib import Path
import shutil
import xml.etree.ElementTree as ET

import pandas as pd
import pyodbc

ROOT = Path(__file__).resolve().parents[2]
EVIDENCE = ROOT / "results/native_build_20261120/ssas"
OUTPUT = EVIDENCE / "readonly_recheck"
DATABASES = ("CoffeeDW_Trang_20261119", "CoffeeDW_Trang_SSIS_TN03_20261120")
MEASURES = ("Sales", "BudgetSales", "Profit", "BudgetProfit", "COGS", "BudgetCOGS", "Margin", "BudgetMargin", "Marketing", "Inventory", "TotalExpenses")
KEYS = ("DateKey", "AreaCode", "ProductName")
DIMENSIONS = ("MonthStart", "DateKey", "AreaCode", "State", "Market", "MarketSize", "ProductName", "ProductLine", "ProductType", "Type", "SourceRow")
DETAIL_SQL = """SELECT d.MonthStart,f.DateKey,l.AreaCode,l.State,l.Market,l.MarketSize,
p.ProductName,p.ProductLine,p.ProductType,p.[Type],f.SourceRow,
""" + ",".join("f." + name for name in MEASURES) + """
 FROM dw.FactSalesPerformance AS f
 JOIN dw.DimDate AS d ON d.DateKey=f.DateKey
 JOIN dw.DimLocation AS l ON l.LocationKey=f.LocationKey
 JOIN dw.DimProduct AS p ON p.ProductKey=f.ProductKey
 ORDER BY f.DateKey,l.AreaCode,p.ProductName"""


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read_database(name):
    if name not in DATABASES:
        raise ValueError("Only the two isolated Trang source databases are permitted.")
    connection = pyodbc.connect("DRIVER={ODBC Driver 18 for SQL Server};SERVER=.;DATABASE=" + name + ";Trusted_Connection=yes;Encrypt=yes;TrustServerCertificate=yes", timeout=15)
    try:
        cursor = connection.cursor()
        cursor.execute(DETAIL_SQL)
        frame = pd.DataFrame.from_records(cursor.fetchall(), columns=[c[0] for c in cursor.description])
        cursor.execute("SELECT COUNT(*) FROM dw.FactSalesPerformance")
        fact_rows = int(cursor.fetchone()[0])
        cursor.execute("SELECT COUNT(*) FROM dw.FactSalesPerformance f WHERE NOT EXISTS (SELECT 1 FROM dw.DimDate d WHERE d.DateKey=f.DateKey) OR NOT EXISTS (SELECT 1 FROM dw.DimLocation l WHERE l.LocationKey=f.LocationKey) OR NOT EXISTS (SELECT 1 FROM dw.DimProduct p WHERE p.ProductKey=f.ProductKey)")
        orphan_rows = int(cursor.fetchone()[0])
        cursor.execute("SELECT (SELECT COUNT(*) FROM dw.DimDate),(SELECT COUNT(*) FROM dw.DimLocation),(SELECT COUNT(*) FROM dw.DimProduct)")
        dimension_rows = [int(value) for value in cursor.fetchone()]
        if fact_rows != len(frame) or fact_rows != 4248 or orphan_rows != 0:
            raise RuntimeError(f"Source grain/joins invalid in {name}.")
        if frame.duplicated(list(KEYS)).any():
            raise RuntimeError(f"Duplicate business grain in {name}.")
        return frame, {"database": name, "fact_rows": fact_rows, "joined_rows": len(frame), "orphan_rows": orphan_rows,
                       "date_rows": dimension_rows[0], "location_rows": dimension_rows[1], "product_rows": dimension_rows[2],
                       "months": int(frame.MonthStart.nunique()), "markets": int(frame.Market.nunique())}
    finally:
        connection.close()


def local_designer_config():
    path = ROOT / "ssas/CoffeeCubeTrang/CoffeeCube.dwproj.user"
    root = ET.parse(path).getroot()
    options = root.find("Configurations/Configuration[Name='Development']/Options")
    server, database = options.findtext("TargetServer"), options.findtext("TargetDatabase")
    bin_target = ROOT / "ssas/CoffeeCubeTrang/bin/CoffeeCube.deploymenttargets"
    built = ET.parse(bin_target).getroot() if bin_target.exists() else None
    return {"local_user_file": str(path.relative_to(ROOT)), "configuration": "Development", "target_server": server, "target_database": database,
            "isolated_target_correct": (server, database) == (r"localhost\TRANGTRETRAU", "CoffeeCube_Trang_20261120"),
            "built_target_server": built.findtext("Server") if built is not None else None,
            "built_target_database": built.findtext("Database") if built is not None else None,
            "note": "The build output must be regenerated by Visual Studio after changing local deployment properties."}


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    frames, profiles = [], []
    for database in DATABASES:
        frame, profile = read_database(database)
        frames.append(frame)
        profiles.append(profile)
    left = frames[0].sort_values(list(KEYS)).reset_index(drop=True)
    right = frames[1].sort_values(list(KEYS)).reset_index(drop=True)
    # SourceRow points into the input file for its ETL batch. The incremental
    # replay file can number the same business observation differently from the
    # original full CSV. Compare lineage separately, never hide the difference.
    pd.testing.assert_frame_equal(left.drop(columns="SourceRow"), right.drop(columns="SourceRow"), check_dtype=False, check_exact=True)
    lineage_difference = left.SourceRow.ne(right.SourceRow)
    lineage = left.loc[lineage_difference, ["MonthStart", *KEYS, "SourceRow"]].rename(columns={"SourceRow": "ExistingSourceRow"})
    lineage["SSISSourceRow"] = right.loc[lineage_difference, "SourceRow"].to_numpy()
    lineage.to_csv(OUTPUT / "source_row_lineage_differences.csv", index=False, encoding="utf-8-sig")
    totals = []
    for measure in MEASURES:
        first, second = left[measure].sum(), right[measure].sum()
        if first != second:
            raise RuntimeError("Measure mismatch: " + measure)
        totals.append({"Measure": measure, "ExistingSQLSource": str(first), "SSISSource": str(second), "Delta": str(second - first)})
    pd.DataFrame(totals).to_csv(OUTPUT / "source_measure_totals.csv", index=False, encoding="utf-8-sig")
    source_a = left.groupby(["MonthStart", "Market"], as_index=False)[list(MEASURES)].sum()
    source_b = right.groupby(["MonthStart", "Market"], as_index=False)[list(MEASURES)].sum()
    pd.testing.assert_frame_equal(source_a, source_b, check_exact=True)
    if len(source_a) != 96:
        raise RuntimeError("Expected 96 Market-month cells.")
    source_a.to_csv(OUTPUT / "canonical_monthly_source.csv", index=False, encoding="utf-8-sig")

    # Compare the fresh read-only MDX exports against the same independent SQL
    # expected values used for acceptance. Source parity above verifies no fact,
    # dimension or amount changed while restoring the SSIS trial database.
    actual_source = EVIDENCE / "readonly_recheck_mdx"
    if not (actual_source / "execution.json").exists():
        raise FileNotFoundError("Run read_cases.ps1 with readonly_recheck_mdx output first.")
    actual_target = OUTPUT / "mdx_actual"
    actual_target.mkdir(exist_ok=True)
    for file in actual_source.glob("*"):
        if file.is_file():
            shutil.copy2(file, actual_target / file.name)
    shutil.copy2(EVIDENCE / "acceptance_cases.json", OUTPUT / "acceptance_cases.json")
    spec = importlib.util.spec_from_file_location("native_mdx_comparison", Path(__file__).with_name("compare_cases.py"))
    comparison = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(comparison)
    comparison.EVIDENCE = OUTPUT
    comparison.main()
    compared = json.loads((OUTPUT / "comparison.json").read_text(encoding="utf-8"))
    environment = json.loads((EVIDENCE / "readonly_recheck_environment.json").read_text(encoding="utf-8-sig"))
    metadata = environment["owned_cube_metadata"]
    if metadata["state"] != "Processed" or metadata["inventory_aggregate"] != "LastChild":
        raise RuntimeError("SSAS metadata no longer matches the accepted LastChild publication.")
    for dimension in metadata["dimensions"]:
        if any(dimension[prop] != "ReportAndStop" for prop in ("key_duplicate", "key_not_found", "null_key_not_allowed", "null_key_converted_to_unknown")):
            raise RuntimeError("Dimension error handling is no longer strict.")
    report = {"status": "passed", "timestamp_utc": datetime.now(timezone.utc).isoformat(), "execution": "read_only_SQL_SELECT_and_ADOMD_and_local_file_inspection",
              "source_databases": profiles, "business_grain": list(KEYS), "source_rows_identical": len(left), "measure_count": len(MEASURES),
              "dimension_columns_compared": [name for name in DIMENSIONS if name != "SourceRow"], "monthly_cells_identical": len(source_a),
              "source_row_lineage_differences": int(lineage_difference.sum()),
              "source_row_difference_months": {str(k): int(v) for k, v in left.loc[lineage_difference].groupby("MonthStart").size().items()},
              "source_row_note": "Compared separately: SourceRow is batch/input-file relative, unlike the canonical business grain. Differences are recorded in source_row_lineage_differences.csv.",
              "surrogate_key_note": "LocationKey/ProductKey IDs may be allocated independently; compared canonical business keys and all dimension attributes instead.",
              "ssas_database": "CoffeeCube_Trang_20261120", "ssas_state": metadata["state"], "inventory_aggregate": metadata["inventory_aggregate"],
              "strict_dimension_error_configuration": True, "mdx_passed": compared["passed"], "mdx_cases": compared["case_count"],
              "local_designer": local_designer_config(), "raw_sha256": sha(ROOT / "data/raw/Coffee.csv"),
              "database_writes_executed": False, "deploy_or_process_executed": False,
              "files": [{"path": p.relative_to(ROOT).as_posix(), "sha256": sha(p)} for p in sorted(OUTPUT.rglob("*")) if p.is_file() and p.name != "verification.json"]}
    (OUTPUT / "verification.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"status": report["status"], "source_rows_identical": len(left), "measures": len(MEASURES), "monthly_cells_identical": len(source_a), "mdx_passed": report["mdx_passed"], "target_correct": report["local_designer"]["isolated_target_correct"], "server_writes": False}))


if __name__ == "__main__":
    main()
